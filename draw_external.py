"""Extend only the three external connections; no changes to the internal netlist."""
def draw_external(add,rect,text,line,circle,C):
    def path(d,stroke,width,extra=''):
        add(f'<path d="{d}" fill="none" stroke="{stroke}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round" {extra}/>')
    def cord(d,width=26):
        path(d,'#17232f',width)
        path(d,'#4b5965',width-10)
        path(d,'#697986',3)
    def plug_face(x,y,male,color):
        # Illustrative connector face, not a terminal pinout or measured geometry.
        rect(x-62,y-60,124,135,color,'#5d6170',22)
        rect(x-54,y-50,108,104,'#e9c858' if male else '#efd570','#877540',20)
        if male:
            for dx in (-24,24):
                rect(x+dx-6,y-32,12,39,'#bcc3c9','#626d76',2)
                rect(x+dx-3,y-27,3,23,'#f0f3f5','#f0f3f5',1)
            circle(x,y+31,9,'#b5bdc5','#626d76')
            circle(x-24,y-3,2,'#697682','#697682');circle(x+24,y-3,2,'#697682','#697682')
        else:
            rect(x-29,y-31,10,34,'#273340','#273340',2)
            rect(x+20,y-31,8,34,'#273340','#273340',2)
            add(f'<path d="M {x-10},{y+37} v -9 a 10,10 0 0 1 20,0 v 9 z" fill="#273340"/>')
    # INPUT: continue the existing outer jacket down to an illustrative grounded plug.
    add('<g class="external" id="external-input" data-ids="01 06 10">')
    cord('M 330,1398 L 330,1560')
    rect(308,1540,44,44,'#bfa746','#86722d',6)
    plug_face(330,1630,True,'#d9b443')
    text(425,1606,'INPUT MALE PLUG',23,weight=700)
    text(425,1637,'NEMA 5-15P candidate',19,color='#63768a')
    text(425,1666,'Three-conductor power cord',18,color='#63768a')
    path('M 330,1718 L 330,1798','#8290a0',3,'stroke-dasharray="6 7"')
    text(355,1760,'Plugs into',18,color='#63768a')
    # A grounded wall receptacle, isolated from the measuring-box protective earth node.
    rect(246,1810,168,198,'#f0efe9','#9da8b3',13)
    circle(330,1828,4,'#c8cdd2','#87939f');circle(330,1990,4,'#c8cdd2','#87939f')
    rect(276,1850,108,115,'#fafaf5','#c1c8cc',24)
    rect(299,1870,10,36,'#273340','#273340',2)
    rect(351,1870,8,36,'#273340','#273340',2)
