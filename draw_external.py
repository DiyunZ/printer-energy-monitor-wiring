    # OUTPUT: box female connector mates with the printer's original male plug.
    add('<g class="external" id="external-output" data-ids="03 07 11">')
    cord('M 900,1398 L 900,1560')
    rect(878,1540,44,44,'#bfa746','#86722d',6)
    plug_face(900,1630,False,'#d9b443')
    text(1000,1606,'OUTPUT FEMALE CONNECTOR',22,weight=700)
    text(1000,1637,'NEMA 5-15R candidate',19,color='#63768a')
    text(1000,1666,'Receives the printer power plug',18,color='#63768a')
